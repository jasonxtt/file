#!/usr/bin/env bash
# Builds config_rust_up.zip: the incremental configuration package of the native (Rust)
# MosDNS, the counterpart of build_config_up.sh for config_up.zip. The managed files are
# taken straight from config_rust/ (no second source tree), listed in the manifest with their
# sha256, and zipped with manifest.json.
#
# Keep SCHEMA/PACKAGE_ID in sync with the program:
#   mosdns-rust rust/native-host/src/update/mod.rs REQUIRED_CONFIG_SCHEMA / REQUIRED_CONFIG_PACKAGE_ID
# (scripts/generate-rust-update-manifest.sh in mosdns-rust refuses a release when they differ).
# Binary-only releases leave both unchanged; a structural change of the managed files bumps both.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SOURCE_DIR="${ROOT_DIR}/config_rust"
OUTPUT_ZIP="${ROOT_DIR}/config_rust_up.zip"

SCHEMA=5
PACKAGE_ID="rust-config-schema-5"

# Structure files the updater may replace. Not listed (never touched): sub_config/special_groups.yaml
# (generated by the host), rule/, gen/, srs/, adguard/, cache/, ui/ and webinfo/ (user and runtime data).
managed_files=("config_custom.yaml")
while IFS= read -r rel; do
  managed_files+=("${rel}")
done < <(cd "${SOURCE_DIR}" && find sub_config -maxdepth 1 -type f -name '*.yaml' ! -name 'special_groups.yaml' | LC_ALL=C sort)

# Switch state files that must exist (created only when missing, same defaults as config_up).
create_if_missing='{}'
deleted_files=("sub_config/switch.yaml")

managed_json="$(printf '%s\n' "${managed_files[@]}" | jq -R . | jq -s .)"
if [[ ${#deleted_files[@]} -gt 0 ]]; then
  deleted_json="$(printf '%s\n' "${deleted_files[@]}" | jq -R . | jq -s .)"
else
  deleted_json='[]'
fi
hashes='{}'
for rel in "${managed_files[@]}"; do
  file="${SOURCE_DIR}/${rel}"
  if [[ ! -f "${file}" ]]; then
    echo "missing managed file: ${rel}" >&2
    exit 1
  fi
  digest="$(shasum -a 256 "${file}" | awk '{print $1}')"
  hashes="$(jq --arg path "${rel}" --arg digest "${digest}" '. + {($path): $digest}' <<<"${hashes}")"
done

stage="$(mktemp -d)"
tmp_zip="$(mktemp "${ROOT_DIR}/.config_rust_up.XXXXXX.zip")"
trap 'rm -rf "${stage}" "${tmp_zip}"' EXIT
rm -f "${tmp_zip}"

jq -n \
  --arg channel "rust" \
  --arg package_id "${PACKAGE_ID}" \
  --argjson format 1 \
  --argjson config_schema "${SCHEMA}" \
  --argjson managed_files "${managed_json}" \
  --argjson create_if_missing "${create_if_missing}" \
  --argjson deleted_files "${deleted_json}" \
  --argjson sha256 "${hashes}" \
  '{
    format: $format,
    channel: $channel,
    package_id: $package_id,
    config_schema: $config_schema,
    managed_files: $managed_files,
    create_if_missing: $create_if_missing,
    delete_files: $deleted_files,
    sha256: $sha256
  }' >"${stage}/manifest.json"

for rel in "${managed_files[@]}"; do
  mkdir -p "${stage}/$(dirname "${rel}")"
  cp "${SOURCE_DIR}/${rel}" "${stage}/${rel}"
done
(
  cd "${stage}"
  zip -X -q "${tmp_zip}" "manifest.json" "${managed_files[@]}"
)
mv "${tmp_zip}" "${OUTPUT_ZIP}"
trap 'rm -rf "${stage}"' EXIT

echo "built ${OUTPUT_ZIP} (schema=${SCHEMA}, package_id=${PACKAGE_ID}, files=${#managed_files[@]})"
echo "sha256: $(shasum -a 256 "${OUTPUT_ZIP}" | awk '{print $1}')"
